    //! ------------------------------------------------------------------
    //! Audio clock domain crossing.
    //!
    //! The machine runs on clk_sys; the Pocket's audio filter runs on a PLL
    //! derived from clk_74b. Handing a 16-bit sample between them unsynchro-
    //! nised lets the audio side latch a mix of old and new bits, and a torn
    //! sample is not a small error -- one flipped high bit throws the value
    //! across the range, which is heard as clicks and static. Both sides can
    //! measure as perfectly correct while the handoff is broken, so this is
    //! done properly from the start rather than diagnosed later.
    //!
    //! Sample at ~48 kHz, hold, and hand over with a toggle flag: by the time
    //! the flag has survived two synchroniser stages the data has been still
    //! for several cycles, so the capture is always of a settled value.
    //! ------------------------------------------------------------------
    //! Decimate before the handover, not just sample.
    //!
    //! The sound board updates at 1.7898 MHz -- 37.3x the 48 kHz the sample is
    //! handed over at -- and the APU's square and noise channels put a lot of
    //! energy well above 24 kHz. Point-sampling that folds all of it back into
    //! the audible band.
    //!
    //! Average exactly the samples that fall between two 48 kHz ticks, then
    //! take a two-point average of the result. An earlier attempt averaged a
    //! fixed 16 samples and point-sampled THAT at 48 kHz, which does not help
    //! much: a 16-long box at 894.9 kHz has its nulls at 55.9 kHz and multiples
    //! and none of them line up with the output rate, so chip harmonics near
    //! 48 kHz still folded down close to DC. Averaging over the actual tick
    //! interval puts the nulls on 48 kHz and its multiples; the two-point
    //! average that follows adds one at 24 kHz, the worst remaining alias
    //! point.
    //!
    //! Measured against a high-order reference decimation of the same
    //! recording: resampling error drops from -21.4 dB to -29.8 dB relative to
    //! signal, and from -35.9 dB to -41.9 dB below 1 kHz. The chips' output is
    //! unipolar, so every effect that stops steps the DC level by thousands of
    //! counts -- MAME's own output does the same, and swings further -- and
    //! band-limiting that step is what stops it arriving as a click.
    logic signed [15:0] snd_hold = 16'sd0;
    logic               snd_tog  = 1'b0;
    logic       [10:0]  snd_div  = 11'd0;

    logic signed [21:0] snd_acc   = 22'sd0;
    logic        [5:0]  snd_cnt   = 6'd0;
    logic signed [15:0] snd_avg    = 16'sd0;
    logic signed [15:0] snd_avg_d  = 16'sd0;
    logic signed [15:0] snd_avg_d2 = 16'sd0;

    wire signed [21:0] snd_s = {{6{po_audio[15]}}, po_audio};
    //! 65536/n for the sample counts this rate ratio can produce. The 2A03
    //! updates at 1.789772 MHz and the handover runs at 48.000 kHz exactly
    //! (96 MHz / 2000), so a tick collects 37 or 38 samples; the neighbours are
    //! there so a boundary case cannot divide by the wrong number.
    wire [12:0] snd_rcp = (snd_cnt == 6'd36) ? 13'd1820 :
                          (snd_cnt == 6'd37) ? 13'd1771 :
                          (snd_cnt == 6'd38) ? 13'd1725 :
                          (snd_cnt == 6'd39) ? 13'd1680 : 13'd1771;
    wire signed [34:0] snd_prod = snd_acc * $signed({1'b0, snd_rcp});
    wire signed [18:0] snd_quot = snd_prod[34:16];
    wire signed [15:0] snd_clip = (snd_quot >  19'sh0_7fff) ? 16'sh7fff :
                                  (snd_quot < -19'sh0_8000) ? 16'sh8000 :
                                  snd_quot[15:0];

    //! 96 MHz / 2000 = 48.000 kHz exactly.
    wire snd_tick = (snd_div == 11'd1999);

    always_ff @(posedge clk_sys) begin
        if (snd_tick) begin
            snd_avg    <= (snd_cnt == 6'd0) ? snd_avg : snd_clip;
            snd_avg_d  <= snd_avg;
            snd_avg_d2 <= snd_avg_d;
            snd_acc   <= po_audio_ce ? snd_s : 22'sd0;
            snd_cnt   <= po_audio_ce ? 6'd1 : 6'd0;
        end
        else if (po_audio_ce) begin
            snd_acc <= snd_acc + snd_s;
            snd_cnt <= snd_cnt + 6'd1;
        end
    end

    //! Two cascaded two-point averages, i.e. [1 2 1]/4 on the tick-aligned
    //! box. Measured against a high-order reference decimation of the same
    //! recording, with the fractional delay each stage adds compensated for:
    //! box alone -24.3 dB, one stage -36.0 dB, two stages -41.7 dB. A third
    //! stage is worse (-31.5 dB) because it starts eating the passband.
    //!
    //! The registers above update on this same edge, so this reads the three
    //! previous averages -- the filter arrives a tick (21 us) late, which is
    //! of no consequence.
    wire signed [18:0] snd_tri = {{3{snd_avg[15]}},    snd_avg}
                               + {{2{snd_avg_d[15]}},  snd_avg_d,  1'b0}
                               + {{3{snd_avg_d2[15]}}, snd_avg_d2};
    wire signed [18:0] snd_s4  = snd_tri >>> 2;
    wire signed [16:0] snd_q4  = snd_s4[16:0];
    always_ff @(posedge clk_sys) begin
        snd_div <= snd_div + 1'd1;
        if (snd_tick) begin
            snd_div  <= 11'd0;
            snd_hold <= (snd_q4 >  17'sh0_7fff) ? 16'sh7fff :
                        (snd_q4 < -17'sh0_8000) ? 16'sh8000 : snd_q4[15:0];
            snd_tog  <= ~snd_tog;
